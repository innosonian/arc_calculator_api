def get_guideline_key(
    manikin_type: str = "ADULT",
    guideline: str = "AHA2020",
    cpr_type: str = "302",
) -> str:
    if not _is_valid_condition(manikin_type, guideline, cpr_type):
        raise ValueError("Invalid guideline conditions")

    return f"{guideline.upper()}_{manikin_type.upper()}_{cpr_type}"


def _is_valid_condition(
    manikin_type: str = "ADULT",
    guideline: str = "AHA2020",
    cpr_type: str = "302",
) -> bool:
    return (
        manikin_type.upper() in ["ADULT", "CHILD", "INFANT"]
        and guideline.upper() in ["AHA2020", "ARC2020", "ARC2025", "ERC2020", "STD2015", "HSTM2015"]
        and cpr_type in ["302", "152"]
    )


